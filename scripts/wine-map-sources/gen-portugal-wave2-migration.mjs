// Emit the Portugal wave-2 boundary migration from the freguesia-union
// artifact. Two jobs:
//
//  1. Correct the Douro. Wave 1 built portugal.douro (and DO Douro / DO Porto,
//     which share its footprint) from a concelho list taken off a tourism site
//     rather than from DL 173/2009. It included four Tavora-Varosa concelhos
//     and omitted four the statute names, giving 4596 km2 against a true
//     2824 km2. The old boundaries are retired, not deleted, so the mistake
//     stays auditable.
//  2. Add the five sub-regions that have an administrative delimitation: the
//     Douro's three (DL 173/2009 lists freguesias explicitly) and the
//     Alentejo's Vidigueira and Granja-Amareleja (Portaria 296/2010 defines
//     those two by whole concelhos and whole freguesias; the other six it
//     defines by ridgelines, watercourses, roads and numbered rural properties,
//     which no union of administrative units can represent).
//
// Usage: node scripts/wine-map-sources/gen-portugal-wave2-migration.mjs
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const OUT = "supabase/migrations/20260904100000_portugal_wave2_freguesia_subregions.sql";
const ART = "data/wine-map/portugal-freguesias-dissolved.geojson";

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex").toUpperCase();
const sq = (s) => String(s).replace(/'/g, "''");

// footprint slug -> places it covers. The Douro region and both its DOs are one
// zone, exactly as in wave 1.
const ZONES = [
  ["douro", ["portugal.douro", "portugal.douro.porto", "portugal.douro.douro"], true],
  ["douro-baixo-corgo", ["portugal.douro.baixo-corgo"], false],
  ["douro-cima-corgo", ["portugal.douro.cima-corgo"], false],
  ["douro-douro-superior", ["portugal.douro.douro-superior"], false],
  ["alentejo-vidigueira", ["portugal.alentejo.vidigueira"], false],
  ["alentejo-granja-amareleja", ["portugal.alentejo.granja-amareleja"], false],
];

const WINDOW = [-9.6, 36.9, -6.1, 42.2];
const REVISION = "20260910T190000Z";

const buf = await readFile(ART);
const art = JSON.parse(buf.toString("utf8"));
const byName = new Map(art.features.map((f) => [f.properties.name, f]));
const checksum = sha256(buf);

let sql = `-- Portugal wave 2: freguesia-level sub-regions, and a correction to the Douro.
--
-- THE CORRECTION. Wave 1 built the Douro from a concelho list taken off a
-- tourism site rather than from the statute. DL 173/2009 art. 2.1 names the
-- concelhos and freguesias of the Regiao Demarcada do Douro, and that list
-- includes Resende, Alfandega da Fe, Mirandela and Figueira de Castelo
-- Rodrigo, which wave 1 omitted, while excluding Moimenta da Beira, Penedono,
-- Sernancelhe and Tarouca, which belong to Tavora-Varosa and which wave 1
-- included. Both lists happen to be 21 concelhos long, which is why the error
-- survived review. The wave-1 footprint measured 4596 km2 against a true
-- 2824 km2 -- 42% of its area was outside the demarcated region. IVDP puts the
-- RDD at roughly 250 000 ha, which the new figure matches and the old did not.
--
-- The wrong boundaries are retired (is_current = false), not deleted, so the
-- correction stays auditable in the boundary history.
--
-- THE SUB-REGIONS. Five of the eleven boundary-less sub-regions have an
-- administrative delimitation and get geometry here. The Douro's three are
-- listed freguesia by freguesia in DL 173/2009. Of the Alentejo's eight,
-- Portaria 296/2010 defines Vidigueira as exactly the concelhos of Alvito,
-- Cuba and Vidigueira, and Granja-Amareleja as the whole concelho of Mourao
-- plus the whole freguesias of Amareleja and Povoa de Sao Miguel -- both
-- legally exact rather than approximations. The remaining six (Borba, Evora,
-- Moura, Portalegre, Redondo, Reguengos) are delimited by the serra d'Ossa
-- ridgeline, river courses, named roads, a railway line, numbered rustic
-- properties and a 700 m altitude cut. No union of administrative units can
-- represent them, so they stay Details-only by necessity rather than by
-- backlog.
--
-- Caveat carried in generation_parameters: DL 173/2009 states its outlines are
-- those in force in 1921, so present-day freguesia geometry approximates the
-- legal area even before the 2013 amalgamations, and freguesias the statute
-- includes only in part (or via named quintas) are included whole.
--
-- Generated by scripts/wine-map-sources/gen-portugal-wave2-migration.mjs.

begin;

-- Retire the wave-1 Douro footprint on all three places that shared it.
update wine_place_boundaries b
set is_current = false
from wine_places p
where p.id = b.wine_place_id
  and p.canonical_key in ('portugal.douro', 'portugal.douro.porto', 'portugal.douro.douro')
  and b.is_current;

`;

for (const [slug, keys, isCorrection] of ZONES) {
  const feat = byName.get(slug);
  if (!feat) throw new Error(`footprint ${slug} missing from ${ART}`);
  const props = feat.properties;
  sql += `-- ${slug}: ${props.units} CAOP units${isCorrection ? " (replaces the retired wave-1 footprint)" : ""}${keys.length > 1 ? `, shared by ${keys.length} places` : ""}.
with src as (
  insert into wine_boundary_sources (source_namespace, source_feature_id, authority, jurisdiction)
  values ('CAOP_FREGUESIAS', 'caop2025-freguesia-union:${slug}', 'Direção-Geral do Território', 'Portugal')
  on conflict (source_namespace, source_feature_id) do update set authority = excluded.authority
  returning id
),
snap as (
  insert into wine_boundary_source_snapshots (
    source_id, source_revision, retrieved_at, source_url, licence,
    normalized_artifact_uri, normalized_checksum_sha256, provenance_note, importer_version
  )
  select id, '${REVISION}', now(),
         'https://ogcapi.dgterritorio.gov.pt/collections/freguesias',
         'CC BY 4.0 — © Direção-Geral do Território',
         '${ART}', '${checksum}',
         '${sq(props.legal ?? `Freguesia-union footprint ${slug}`)}',
         'scripts/wine-map-sources/build-portugal-freguesia-union.mjs'
  from src returning id
),
geom as (
  select extensions.ST_Multi(extensions.ST_CollectionExtract(extensions.ST_MakeValid(
    extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON('${JSON.stringify(feat.geometry)}'), 4326)), 3)) g
)
insert into wine_place_boundaries (
  wine_place_id, source_snapshot_id, boundary_method, quality_status,
  display_geometry, label_point, bbox, source_feature_refs,
  generation_parameters, revision, is_current, reviewed_at
)
select p.id, snap.id, 'GENERALIZED_FROM_OFFICIAL_SOURCE', 'VALIDATED', geom.g,
       extensions.ST_PointOnSurface(geom.g),
       array[extensions.ST_XMin(extensions.Box3D(geom.g)), extensions.ST_YMin(extensions.Box3D(geom.g)),
             extensions.ST_XMax(extensions.Box3D(geom.g)), extensions.ST_YMax(extensions.Box3D(geom.g))]::double precision[],
       jsonb_build_object('footprint', '${slug}', 'caop_units', ${props.units},
                          'statute_freguesias', ${props.statute_names},
                          'whole_concelhos', ${props.whole_concelhos}),
       jsonb_build_object(
         'engine', 'caop2025-freguesia-union',
         'simplify', 'mapshaper 6% Visvalingam, keep-shapes',
         'holes', 'dropped',
         'min_part_area_deg2', 0.00001,
         'coordinate_precision', 5,
         'partial_units', 'included whole',
         'partial_notes', '${sq(JSON.stringify(props.partial ?? {}))}'::jsonb,
         'boundary_epoch', 'DL 173/2009 delimits by the administrative boundaries in force in 1921',
         'shares_zone_with', ${keys.length > 1 ? `jsonb_build_array(${keys.map((k) => `'${k}'`).join(", ")})` : "null"}
       ),
       '${REVISION}', true, now()
from wine_places p, snap, geom
where p.canonical_key in (${keys.map((k) => `'${k}'`).join(", ")});

`;
}

const inserted = ZONES.reduce((n, [, keys]) => n + keys.length, 0);
sql += `do $$
declare
  n int;
  bad record;
  old_km2 numeric;
  new_km2 numeric;
begin
  -- Exactly one current boundary per place touched, and the retired ones stay.
  select count(*) into n
  from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
  where p.canonical_key like 'portugal%' and b.is_current and b.revision = '${REVISION}';
  if n <> ${inserted} then
    raise exception 'expected ${inserted} new current boundaries, got %', n;
  end if;

  for bad in
    select p.canonical_key, count(*) c
    from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
    where p.canonical_key like 'portugal%' and b.is_current
    group by 1 having count(*) <> 1
  loop
    raise exception '% has % current boundaries', bad.canonical_key, bad.c;
  end loop;

  select count(*) into n
  from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
  where p.canonical_key in ('portugal.douro', 'portugal.douro.porto', 'portugal.douro.douro')
    and not b.is_current;
  if n <> 3 then raise exception 'expected 3 retired douro boundaries, got %', n; end if;

  -- The correction must actually shrink the Douro towards the IVDP figure of
  -- roughly 250 000 ha. A regression that quietly restored the old footprint
  -- would otherwise pass every other gate here.
  select round((extensions.ST_Area(b.display_geometry::extensions.geography) / 1e6)::numeric)
    into new_km2
  from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
  where p.canonical_key = 'portugal.douro' and b.is_current;
  if new_km2 not between 2400 and 3200 then
    raise exception 'corrected Douro is % km2, outside the expected 2400-3200 band', new_km2;
  end if;
  select round((extensions.ST_Area(b.display_geometry::extensions.geography) / 1e6)::numeric)
    into old_km2
  from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
  where p.canonical_key = 'portugal.douro' and not b.is_current;
  if old_km2 <= new_km2 then
    raise exception 'retired Douro (% km2) is not larger than the correction (% km2)', old_km2, new_km2;
  end if;

  -- Every new sub-region must sit inside its region. Region and sub-region are
  -- simplified independently, so overlap area is the test, not ST_Within.
  for bad in
    select c.canonical_key,
           extensions.ST_Area(extensions.ST_Intersection(cb.display_geometry, pb.display_geometry))
             / nullif(extensions.ST_Area(cb.display_geometry), 0) as inside
    from wine_places c
    join wine_places parent on parent.id = c.primary_parent_id
    join wine_place_boundaries cb on cb.wine_place_id = c.id and cb.is_current
    join wine_place_boundaries pb on pb.wine_place_id = parent.id and pb.is_current
    where c.kind = 'SUBREGION' and c.canonical_key like 'portugal.%'
  loop
    if bad.inside is null or bad.inside < 0.995 then
      raise exception 'sub-region % lies only %%% inside its region',
        bad.canonical_key, round((coalesce(bad.inside, 0) * 100)::numeric, 3);
    end if;
  end loop;

  for bad in
    select p.canonical_key, b.bbox
    from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
    where b.revision = '${REVISION}' and b.is_current
      and (b.bbox[1] < ${WINDOW[0]} or b.bbox[2] < ${WINDOW[1]}
        or b.bbox[3] > ${WINDOW[2]} or b.bbox[4] > ${WINDOW[3]})
  loop
    raise exception 'boundary for % escapes the mainland window: %', bad.canonical_key, bad.bbox;
  end loop;
end $$;

commit;
`;

await writeFile(OUT, sql);
console.log(`WROTE ${OUT} bytes=${Buffer.byteLength(sql)} zones=${ZONES.length} boundaries=${inserted}`);
