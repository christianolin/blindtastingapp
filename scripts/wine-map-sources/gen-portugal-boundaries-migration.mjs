// Emit the Portugal wave-1 boundary migration from the two normalized
// artifacts: the Natural Earth country outline and the CAOP concelho-union
// footprints (plus the CAOP RAM Madeira footprint).
//
// Several places legitimately share one footprint — Douro/Porto/DO Douro are
// the same demarcated region, as are Madeira/Madeirense and Palmela/Setúbal.
// Each gets its own boundary row against the same snapshot, with
// generation_parameters.shares_zone_with naming the others, which is the
// pattern 20260902220000_italy_missing_geometry.sql established.
//
// Usage: node scripts/wine-map-sources/gen-portugal-boundaries-migration.mjs
// Wave 1 was run from .tiles-build/portugal/, which is the path recorded in
// the snapshots' importer_version; the script is tracked here so the wave is
// reproducible. Later waves should run it from this path.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const OUT = "supabase/migrations/20260903110000_portugal_wave1_boundaries.sql";
const CONCELHOS = "data/wine-map/portugal-concelhos-dissolved.geojson";
const MADEIRA = "data/wine-map/madeira-rdm-caop.geojson";
const COUNTRY = "data/wine-map/portugal-mainland-ne50m.geojson";

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex").toUpperCase();
const sq = (s) => s.replace(/'/g, "''");

// footprint slug -> the places it covers, most significant first.
const ZONES = [
  ["douro", ["portugal.douro", "portugal.douro.porto", "portugal.douro.douro"]],
  ["minho", ["portugal.minho", "portugal.minho.vinho-verde"]],
  ["minho-moncao-melgaco", ["portugal.minho.moncao-e-melgaco"]],
  ["minho-lima", ["portugal.minho.lima"]],
  ["minho-cavado", ["portugal.minho.cavado"]],
  ["minho-ave", ["portugal.minho.ave"]],
  ["minho-basto", ["portugal.minho.basto"]],
  ["minho-sousa", ["portugal.minho.sousa"]],
  ["minho-amarante", ["portugal.minho.amarante"]],
  ["minho-baiao", ["portugal.minho.baiao"]],
  ["minho-paiva", ["portugal.minho.paiva"]],
  ["dao", ["portugal.dao", "portugal.dao.dao"]],
  ["bairrada", ["portugal.bairrada", "portugal.bairrada.bairrada"]],
  ["alentejo", ["portugal.alentejo", "portugal.alentejo.alentejo"]],
  ["peninsula-de-setubal", ["portugal.peninsula-de-setubal"]],
  ["palmela", ["portugal.peninsula-de-setubal.palmela", "portugal.peninsula-de-setubal.setubal"]],
];

// Every mainland footprint must sit inside the CAOP mainland window; Madeira
// has its own. A bbox guard per place is what caught the Italian regressions.
const MAINLAND_WINDOW = [-9.6, 36.9, -6.1, 42.2];
const MADEIRA_WINDOW = [-17.4, 32.5, -16.2, 33.2];

const concelhoBuf = await readFile(CONCELHOS);
const madeiraBuf = await readFile(MADEIRA);
const countryBuf = await readFile(COUNTRY);
const concelhos = JSON.parse(concelhoBuf.toString("utf8"));
const madeira = JSON.parse(madeiraBuf.toString("utf8"));
const country = JSON.parse(countryBuf.toString("utf8"));

const byName = new Map(concelhos.features.map((f) => [f.properties.name, f]));
const REVISION = "20260910T000000Z";

let sql = `-- Portugal wave 1 boundaries.
--
-- Country: Natural Earth 1:50m admin-0 PRT, mainland components only, the same
-- extractor France/Italy/Spain use. Madeira is deliberately not in the country
-- outline: Natural Earth 1:50m resolves the island in twelve points and omits
-- Porto Santo, so the Madeira REGION carries its own far better CAOP RAM
-- geometry and stands alone in the Atlantic, which is what "Portugal
-- Continental" means in every Portuguese source.
--
-- Everything else: concelho-union of CAOP 2025 (Direção-Geral do Território,
-- CC BY 4.0) driven by the legal area definitions published by the IVV, the
-- IVDP and the regional CVRs — the method Italy uses over ISTAT comuni. No
-- Portuguese authority publishes open DO boundaries, so this is the best
-- available source; concelhos that the legal text includes only in part are
-- included whole, which is recorded in generation_parameters.
--
-- Generated by .tiles-build/portugal/gen-boundaries-migration.mjs.

begin;

`;

// --- country ---------------------------------------------------------------
sql += `-- Portugal (COUNTRY) — Natural Earth mainland.
with src as (
  insert into wine_boundary_sources (source_namespace, source_feature_id, authority, jurisdiction)
  values ('NATURAL_EARTH', 'ne_50m_admin_0_countries:PRT', 'Natural Earth', 'Portugal')
  on conflict (source_namespace, source_feature_id) do update set authority = excluded.authority
  returning id
),
snap as (
  insert into wine_boundary_source_snapshots (
    source_id, source_revision, retrieved_at, source_url, licence,
    normalized_artifact_uri, normalized_checksum_sha256, provenance_note, importer_version
  )
  select id, '${REVISION}', now(),
         'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson',
         'Public domain (Natural Earth)',
         '${COUNTRY}', '${sha256(countryBuf)}',
         'Natural Earth PRT filtered to components fully inside lon [-9.6,-6.1], lat [36.9,42.2] (mainland only; Madeira and the Azores excluded), rounded to 4 decimals.',
         'scripts/wine-map-tiles/extract-portugal-ne.mjs'
  from src returning id
),
geom as (
  select extensions.ST_Multi(extensions.ST_CollectionExtract(extensions.ST_MakeValid(
    extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON('${JSON.stringify(country.geometry)}'), 4326)), 3)) g
)
insert into wine_place_boundaries (
  wine_place_id, source_snapshot_id, boundary_method, quality_status,
  display_geometry, label_point, bbox, source_feature_refs,
  generation_parameters, revision, is_current, reviewed_at
)
select p.id, snap.id, 'MANUAL', 'VALIDATED', geom.g, extensions.ST_PointOnSurface(geom.g),
       array[extensions.ST_XMin(extensions.Box3D(geom.g)), extensions.ST_YMin(extensions.Box3D(geom.g)),
             extensions.ST_XMax(extensions.Box3D(geom.g)), extensions.ST_YMax(extensions.Box3D(geom.g))]::double precision[],
       jsonb_build_object('adm0_a3', 'PRT', 'dataset', 'ne_50m_admin_0_countries'),
       jsonb_build_object('component_filter', 'outer ring fully inside lon [-9.6,-6.1], lat [36.9,42.2]',
                          'coordinate_precision', 4,
                          'excludes', jsonb_build_array('Madeira', 'Azores')),
       '${REVISION}', true, now()
from wine_places p, snap, geom where p.canonical_key = 'portugal';

`;

// --- mainland concelho-union footprints ------------------------------------
for (const [slug, keys] of ZONES) {
  const feat = byName.get(slug);
  if (!feat) throw new Error(`footprint ${slug} missing from ${CONCELHOS}`);
  const geometry = JSON.stringify(feat.geometry);
  const legal = feat.properties.legal ?? null;
  sql += `-- ${slug}: ${feat.properties.concelho_count} concelhos${keys.length > 1 ? `, shared by ${keys.length} places` : ""}.
with src as (
  insert into wine_boundary_sources (source_namespace, source_feature_id, authority, jurisdiction)
  values ('CAOP_CONCELHOS', 'caop2025-concelho-union:${slug}', 'Direção-Geral do Território', 'Portugal')
  on conflict (source_namespace, source_feature_id) do update set authority = excluded.authority
  returning id
),
snap as (
  insert into wine_boundary_source_snapshots (
    source_id, source_revision, retrieved_at, source_url, licence,
    normalized_artifact_uri, normalized_checksum_sha256, provenance_note, importer_version
  )
  select id, '${REVISION}', now(),
         'https://ogcapi.dgterritorio.gov.pt/collections/municipios',
         'CC BY 4.0 — © Direção-Geral do Território',
         '${CONCELHOS}', '${sha256(concelhoBuf)}',
         '${sq(legal ?? `Concelho-union footprint ${slug}`)}',
         '.tiles-build/portugal/build-concelho-dissolve.mjs'
  from src returning id
),
geom as (
  select extensions.ST_Multi(extensions.ST_CollectionExtract(extensions.ST_MakeValid(
    extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON('${geometry}'), 4326)), 3)) g
)
insert into wine_place_boundaries (
  wine_place_id, source_snapshot_id, boundary_method, quality_status,
  display_geometry, label_point, bbox, source_feature_refs,
  generation_parameters, revision, is_current, reviewed_at
)
select p.id, snap.id, 'GENERALIZED_FROM_OFFICIAL_SOURCE', 'VALIDATED', geom.g,
       extensions.ST_PointOnSurface(geom.g),
       array[extensions.ST_XMin(extensions.Box3D(geom.g)), extensions.ST_YMin(extensions.Box3D(geom.g)),
             extensions.ST_XMax(extensions.Box3D(geom.g)), extensions.ST_YMax(extensions.Box3D(geom.g))]::double precision[],
       jsonb_build_object('footprint', '${slug}', 'concelhos', ${feat.properties.concelho_count}),
       jsonb_build_object(
         'engine', 'caop2025-concelho-union',
         'simplify', 'mapshaper 6% Visvalingam, keep-shapes',
         'holes', 'dropped',
         'min_part_area_deg2', 0.00001,
         'coordinate_precision', 5,
         'partial_concelhos', 'included whole',
         'shares_zone_with', ${keys.length > 1 ? `jsonb_build_array(${keys.map((k) => `'${k}'`).join(", ")})` : "null"}
       ),
       '${REVISION}', true, now()
from wine_places p, snap, geom
where p.canonical_key in (${keys.map((k) => `'${k}'`).join(", ")});

`;
}

// --- Madeira ---------------------------------------------------------------
const madeiraKeys = ["portugal.madeira", "portugal.madeira.madeira", "portugal.madeira.madeirense"];
sql += `-- Madeira: union of the 11 CAOP 2025 (RAM) municipios reduced to the islands
-- of Madeira and Porto Santo, which is the DO area per IVBAM.
with src as (
  insert into wine_boundary_sources (source_namespace, source_feature_id, authority, jurisdiction)
  values ('CAOP_RAM', 'caop2025-ram-union:madeira', 'Direção-Geral do Território', 'Portugal')
  on conflict (source_namespace, source_feature_id) do update set authority = excluded.authority
  returning id
),
snap as (
  insert into wine_boundary_source_snapshots (
    source_id, source_revision, retrieved_at, source_url, licence,
    normalized_artifact_uri, normalized_checksum_sha256, provenance_note, importer_version
  )
  select id, '${REVISION}', now(),
         'https://geo2.dgterritorio.gov.pt/geoserver/caop_ram/wfs (caop_ram:ram_municipios)',
         'CC BY 4.0 — © Direção-Geral do Território',
         '${MADEIRA}', '${sha256(madeiraBuf)}',
         '${sq(madeira.properties.method)}',
         '.tiles-build/portugal/build-madeira.mjs'
  from src returning id
),
geom as (
  select extensions.ST_Multi(extensions.ST_CollectionExtract(extensions.ST_MakeValid(
    extensions.ST_SetSRID(extensions.ST_GeomFromGeoJSON('${JSON.stringify(madeira.geometry)}'), 4326)), 3)) g
)
insert into wine_place_boundaries (
  wine_place_id, source_snapshot_id, boundary_method, quality_status,
  display_geometry, label_point, bbox, source_feature_refs,
  generation_parameters, revision, is_current, reviewed_at
)
select p.id, snap.id, 'GENERALIZED_FROM_OFFICIAL_SOURCE', 'VALIDATED', geom.g,
       extensions.ST_PointOnSurface(geom.g),
       array[extensions.ST_XMin(extensions.Box3D(geom.g)), extensions.ST_YMin(extensions.Box3D(geom.g)),
             extensions.ST_XMax(extensions.Box3D(geom.g)), extensions.ST_YMax(extensions.Box3D(geom.g))]::double precision[],
       jsonb_build_object('footprint', 'madeira', 'municipios', 11),
       jsonb_build_object(
         'engine', 'caop2025-ram-union',
         'simplify', 'mapshaper 6% Visvalingam, keep-shapes',
         'holes', 'dropped',
         'islands', jsonb_build_array('Madeira', 'Porto Santo'),
         'excludes', jsonb_build_array('Desertas', 'Selvagens'),
         'coordinate_precision', 5,
         'shares_zone_with', jsonb_build_array(${madeiraKeys.map((k) => `'${k}'`).join(", ")})
       ),
       '${REVISION}', true, now()
from wine_places p, snap, geom
where p.canonical_key in (${madeiraKeys.map((k) => `'${k}'`).join(", ")});

`;

// --- promotion + guards ----------------------------------------------------
const boundedCount = 1 + ZONES.reduce((n, [, keys]) => n + keys.length, 0) + madeiraKeys.length;
sql += `-- Everything in this wave is researched and sourced; promote the tree.
-- The eleven freguesia-defined sub-regions stay boundary-less on purpose and
-- render as Details-only nodes, which VERIFIED already allows.
update wine_places set publication_status = 'VERIFIED'
where canonical_key like 'portugal.%' and publication_status = 'DRAFT';

do $$
declare
  n int;
  bad record;
begin
  select count(*) into n
  from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
  where p.canonical_key like 'portugal%' and b.is_current and b.quality_status = 'VALIDATED';
  if n <> ${boundedCount} then
    raise exception 'expected ${boundedCount} current portugal boundaries, got %', n;
  end if;

  select count(*) into n from wine_places
  where canonical_key like 'portugal%' and publication_status <> 'VERIFIED';
  if n <> 0 then raise exception '% portugal places are still unpublished', n; end if;

  for bad in
    select p.canonical_key, b.bbox
    from wine_place_boundaries b join wine_places p on p.id = b.wine_place_id
    where p.canonical_key like 'portugal%' and b.is_current
      and case when p.canonical_key like 'portugal.madeira%'
        then b.bbox[1] < ${MADEIRA_WINDOW[0]} or b.bbox[2] < ${MADEIRA_WINDOW[1]}
          or b.bbox[3] > ${MADEIRA_WINDOW[2]} or b.bbox[4] > ${MADEIRA_WINDOW[3]}
        else b.bbox[1] < ${MAINLAND_WINDOW[0]} or b.bbox[2] < ${MAINLAND_WINDOW[1]}
          or b.bbox[3] > ${MAINLAND_WINDOW[2]} or b.bbox[4] > ${MAINLAND_WINDOW[3]}
      end
  loop
    raise exception 'boundary for % escapes its window: %', bad.canonical_key, bad.bbox;
  end loop;

  -- A sub-region that is not inside its region means a concelho list drifted.
  -- Region and sub-region are simplified independently, so their shared edges
  -- wobble by a few hundred metres and strict ST_Within is the wrong test;
  -- overlap area is the invariant that actually encodes membership. Measured
  -- worst case on this wave is 99.90% (Monção e Melgaço, on the border).
  for bad in
    select c.canonical_key,
           extensions.ST_Area(extensions.ST_Intersection(cb.display_geometry, pb.display_geometry))
             / nullif(extensions.ST_Area(cb.display_geometry), 0) as inside
    from wine_places c
    join wine_places parent on parent.id = c.primary_parent_id
    join wine_place_boundaries cb on cb.wine_place_id = c.id and cb.is_current
    join wine_place_boundaries pb on pb.wine_place_id = parent.id and pb.is_current
    where c.canonical_key like 'portugal.minho.%'
      and c.kind = 'SUBREGION'
  loop
    if bad.inside is null or bad.inside < 0.995 then
      raise exception 'sub-region % lies only %%% inside its region',
        bad.canonical_key, round((coalesce(bad.inside, 0) * 100)::numeric, 3);
    end if;
  end loop;
end $$;

commit;
`;

await writeFile(OUT, sql);
console.log(`WROTE ${OUT} bytes=${Buffer.byteLength(sql)} boundaries=${boundedCount}`);
